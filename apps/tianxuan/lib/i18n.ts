export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "en" ? "en" : "zh";
}

export function translate(locale: Locale, key: MessageKey): string {
  return locale === "en" ? en[key] : zh[key];
}

/** 简单占位符替换：`{name}` → params.name，未提供的占位符原样保留。 */
export function formatMessage(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function routeTitleKey(pathname: string): MessageKey {
  const first = pathname.split("/")[1] ?? "";
  if (first === "docs" && pathname.split("/").length > 2) {
    return "shell.docReader";
  }
  switch (first) {
    case "":
      return "nav.home";
    case "docs":
      return "nav.docs";
    case "issues":
      return "nav.issues";
    case "repos":
      return "nav.repos";
    case "requirements":
      return "nav.requirements";
    case "search":
      return "nav.search";
    case "settings":
      return "nav.settings";
    default:
      return "nav.home";
  }
}
