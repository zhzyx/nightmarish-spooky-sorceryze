"""Embed the shared AINative implementation, with no runtime source-tree paths."""

import hashlib
import json
from pathlib import Path


def bundle_files(sources):
    files = {}
    for source in sources:
        path = Path(str(source))
        text = path.read_text(encoding="utf-8")
        if path.suffix == ".gd":
            # Sibling references work in both the installed editor bundle and
            # portable character runtime copies. Do not embed a project mount.
            text = text.replace("res://addons/ainative/", "")
            name = "scripts/" + path.name
        else:
            name = "tools/" + path.name
        files[name] = text
    manifest = {
        "schema_version": 1,
        "runtime_files": {
            Path(name).name: hashlib.sha256(text.encode("utf-8")).hexdigest()
            for name, text in sorted(files.items())
            if name.startswith("scripts/")
        },
    }
    files["manifest.json"] = json.dumps(manifest, sort_keys=True) + "\n"
    return dict(sorted(files.items()))


def build_bundle(target, source, env):
    files = bundle_files(source)
    digest = hashlib.sha256()
    for name, text in files.items():
        digest.update(name.encode("utf-8") + b"\0" + text.encode("utf-8") + b"\0")
    with open(str(target[0]), "w", encoding="utf-8", newline="\n") as output:
        output.write("// Generated by editor/ainative/builders.py. Do not edit.\n#pragma once\n\n")
        output.write('static const char *ainative_bundle_version = "' + digest.hexdigest() + '";\n')
        for index, text in enumerate(files.values()):
            output.write(f"static const char *const ainative_source_{index}[] = {{\n")
            # Keep each literal below the compiler's string literal limit.
            for offset in range(0, len(text), 4096):
                output.write(json.dumps(text[offset : offset + 4096], ensure_ascii=False) + ",\n")
            output.write("nullptr,\n};\n")
        output.write(
            "struct AINativeBundledFile { const char *path; const char *sha256; const char *const *source; };\n"
        )
        output.write("static const AINativeBundledFile ainative_bundle_files[] = {\n")
        for index, (name, text) in enumerate(files.items()):
            sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
            output.write(f'{{"{name}", "{sha}", ainative_source_{index}}},\n')
        output.write("};\n")
